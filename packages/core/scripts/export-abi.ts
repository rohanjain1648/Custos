// Copies the CustosVault ABI and bytecode from the Foundry build into packages/core/src.
// Run after `forge build`:  npm run build:contracts && npm run abi
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../..");
const artifactPath = path.join(root, "contracts/out/CustosVault.sol/CustosVault.json");
const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));

const header = "// Generated by packages/core/scripts/export-abi.ts from contracts/out. Do not edit by hand.\n";
writeFileSync(
  path.join(root, "packages/core/src/vault-abi.ts"),
  `${header}export const custosVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
writeFileSync(
  path.join(root, "packages/core/src/vault-bytecode.ts"),
  `${header}export const custosVaultBytecode = "${artifact.bytecode.object}" as const;\n`,
);
console.log(`ABI (${artifact.abi.length} entries) and bytecode (${(artifact.bytecode.object.length - 2) / 2} bytes) exported.`);
