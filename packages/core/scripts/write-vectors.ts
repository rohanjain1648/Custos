// Writes contracts/test/vectors/custos-vectors.json. The Solidity test `test_MessagesMatchVectors` and the
// TypeScript test `encoding.test.ts` both assert against it, so the two encoders can never drift apart.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { toHex } from "viem";
import {
  approvedPayMessage,
  pauseMessage,
  payMessage,
  payeeMessage,
  policyMessage,
  unpauseMessage,
  withdrawMessage,
} from "../src/encoding";
import {
  VECTOR_CTX as ctx,
  VECTOR_PAUSE,
  VECTOR_PAY,
  VECTOR_PAYEE,
  VECTOR_POLICY,
  VECTOR_UNPAUSE,
  VECTOR_WITHDRAW,
} from "./vector-inputs";

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, "../../../contracts/test/vectors/custos-vectors.json");

const s = (v: bigint) => v.toString();
const vectors = {
  note: "Generated by packages/core/scripts/write-vectors.ts. Asserted by Solidity and TypeScript tests.",
  cosmosChainId: ctx.cosmosChainId,
  chainId: s(ctx.chainId),
  vault: ctx.vault,
  pay: {
    payee: VECTOR_PAY.payee,
    token: VECTOR_PAY.token,
    amount: s(VECTOR_PAY.amount),
    invoiceHash: VECTOR_PAY.invoiceHash,
    nonce: s(VECTOR_PAY.nonce),
    expiry: s(VECTOR_PAY.expiry),
    message: toHex(payMessage(ctx, VECTOR_PAY)),
  },
  approvedPay: { message: toHex(approvedPayMessage(ctx, VECTOR_PAY)) },
  policy: {
    perTxCap: s(VECTOR_POLICY.perTxCap),
    dailyCap: s(VECTOR_POLICY.dailyCap),
    nonce: s(VECTOR_POLICY.nonce),
    expiry: s(VECTOR_POLICY.expiry),
    message: toHex(policyMessage(ctx, VECTOR_POLICY.perTxCap, VECTOR_POLICY.dailyCap, VECTOR_POLICY.nonce, VECTOR_POLICY.expiry)),
  },
  payee: {
    who: VECTOR_PAYEE.who,
    allowed: VECTOR_PAYEE.allowed,
    cap: s(VECTOR_PAYEE.cap),
    nonce: s(VECTOR_PAYEE.nonce),
    expiry: s(VECTOR_PAYEE.expiry),
    message: toHex(
      payeeMessage(ctx, VECTOR_PAYEE.who, VECTOR_PAYEE.allowed, VECTOR_PAYEE.cap, VECTOR_PAYEE.nonce, VECTOR_PAYEE.expiry),
    ),
  },
  pause: { nonce: s(VECTOR_PAUSE.nonce), expiry: s(VECTOR_PAUSE.expiry), message: toHex(pauseMessage(ctx, VECTOR_PAUSE.nonce, VECTOR_PAUSE.expiry)) },
  unpause: {
    nonce: s(VECTOR_UNPAUSE.nonce),
    expiry: s(VECTOR_UNPAUSE.expiry),
    message: toHex(unpauseMessage(ctx, VECTOR_UNPAUSE.nonce, VECTOR_UNPAUSE.expiry)),
  },
  withdraw: {
    to: VECTOR_WITHDRAW.to,
    amount: s(VECTOR_WITHDRAW.amount),
    nonce: s(VECTOR_WITHDRAW.nonce),
    expiry: s(VECTOR_WITHDRAW.expiry),
    message: toHex(
      withdrawMessage(ctx, VECTOR_WITHDRAW.to, VECTOR_WITHDRAW.amount, VECTOR_WITHDRAW.nonce, VECTOR_WITHDRAW.expiry),
    ),
  },
};

writeFileSync(target, JSON.stringify(vectors, null, 2) + "\n");
console.log(`wrote ${path.relative(process.cwd(), target)}`);
