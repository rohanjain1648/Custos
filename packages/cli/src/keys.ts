// npm run keys [-- --force]
// Creates .env with three fresh keys: the owner (treasury, holds the root ML-DSA-87 key), the agent (Keeper
// account, also the Q-Day Drill account) and the linked key (a separate secp256k1 key for treasury top-ups).
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { deriveUnifiedAccount, generateMnemonic } from "@qorechain/sdk";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { TESTNET } from "@custos/core";

const root = process.cwd();
const envPath = path.join(root, ".env");
if (existsSync(envPath) && !process.argv.includes("--force")) {
  console.log(".env already exists. Keeping it (it holds your keys). Use `npm run keys -- --force` to replace it.");
  process.exit(0);
}

const ownerMnemonic = generateMnemonic(256);
const agentMnemonic = generateMnemonic(256);
const linkedKey = generatePrivateKey();
const owner = await deriveUnifiedAccount(ownerMnemonic);
const agent = await deriveUnifiedAccount(agentMnemonic);
const linked = privateKeyToAccount(linkedKey);

writeFileSync(
  envPath,
  `# Custos configuration. Holds secret keys: never commit or share this file.
# Generated by \`npm run keys\` on ${new Date().toISOString()}.

# Network: testnet ${TESTNET.cosmosChainId} (EVM chain id ${TESTNET.evmChainId})

# Owner = the treasury. Its ML-DSA-87 key sets the mandate and approves exceptions.
OWNER_MNEMONIC=${ownerMnemonic}
OWNER_COSMOS_ADDRESS=${owner.cosmos}

# Agent = the Keeper's account (also your Q-Day Drill account). Its ML-DSA-87 key signs payouts.
AGENT_MNEMONIC=${agentMnemonic}

# Linked key = separate secp256k1 key the treasury lets top up the vault (x/abstractaccount rule).
LINKED_KEY_PRIVATE_KEY=${linkedKey}

# Filled in by \`npm run setup:testnet\`.
VAULT_ADDRESS=
VAULT_TOKEN=${TESTNET.fusd.address}

# true = sign and verify everything, broadcast nothing. Set to false after setup to go live.
KEEPER_DRY_RUN=true
KEEPER_PORT=8787
KEEPER_API_TOKEN=${randomBytes(16).toString("hex")}
OWNER_SIGNER_PORT=8788
CONSOLE_PORT=5173
TOP_UP_AMOUNT=200

# Optional: Claude for the Brain. Without it the Brain uses its offline extractor.
ANTHROPIC_API_KEY=
CUSTOS_MODEL=claude-opus-5-5
`,
);

console.log(`Wrote .env with fresh keys.\n`);
console.log(`  owner   ${owner.cosmos}   ${owner.evm}`);
console.log(`  agent   ${agent.cosmos}   ${agent.evm}`);
console.log(`  linked  ${linked.address}\n`);
console.log(`Next:`);
console.log(`  1. Sign in at ${TESTNET.faucet} and claim test tokens for the OWNER address above:`);
console.log(`     ${owner.cosmos}   (100 QOR + 1000 fUSD, once per 24 h)`);
console.log(`  2. npm run setup:testnet`);
